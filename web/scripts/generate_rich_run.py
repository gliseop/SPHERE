def ts(day: int, hour: int, minute: int = 0) -> str:
    """Сформировать ISO-timestamp для дня и часа.

    Args:
        day: Смещение дня от начала (0 = понедельник).
        hour: Час дня.
        minute: Минута.

    Returns:
        Строка ISO 8601.
    """
    dt = START + timedelta(days=day, hours=hour - 9, minutes=minute)
    return dt.isoformat()


