"""Перечисления режимов управления и идентификаторов сценариев."""

from enum import Enum


class GovernanceMode(str, Enum):
    """Режим управления организацией.

    G0 — без контроля, G1 — аудитор (рекомендательный),
    G2 — аудитор с репутацией, G3 — полный (с трибуналом).
    """

    G0 = "G0"
    G1 = "G1"
    G2 = "G2"
    G3 = "G3"


